import sys
import subprocess
from pathlib import Path

import numpy as np
import rasterio
from rasterio.transform import from_origin
from PIL import Image
from huggingface_hub import hf_hub_download


MODEL = "IGNF/FLAIR-INC_rgb_15cl_resnet34-unet"

# FLAIR output classes (the checkpoint has 19 output channels).
CLASSES = [
    "building",
    "pervious surface",
    "impervious surface",
    "bare soil",
    "water",
    "coniferous",
    "deciduous",
    "brushwood",
    "vineyard",
    "herbaceous vegetation",
    "agricultural land",
    "plowed land",
    "swimming pool",
    "snow",
    "clear cut",
    "mixed",
    "ligneous",
    "greenhouse",
    "other",
]


def main():

    if len(sys.argv) != 2:
        print("Usage: python flair_inference.py image.tif")
        sys.exit(1)

    image_path = Path(sys.argv[1]).resolve()

    if not image_path.exists():
        sys.exit(f"Image not found: {image_path}")

    # Download the checkpoint automatically (cached by Hugging Face).
    print("Loading FLAIR checkpoint...")
    weights = hf_hub_download(
        repo_id=MODEL,
        filename="FLAIR-INC_rgb_15cl_resnet34-unet_weights.pth",
    )

    needs_pixel_transform = False
    with rasterio.open(image_path) as src:
        if src.count < 3:
            sys.exit("Expected an image with at least 3 bands.")

        print(f"Image size: {src.width} x {src.height}")
        print(f"Number of bands: {src.count}")
        print(f"Data type: {src.dtypes[0]}")

        if src.dtypes[0] != "uint8":
            sys.exit(
                "This checkpoint expects 8-bit RGB imagery. "
                "Convert the input to 8-bit RGB before testing."
            )
        needs_pixel_transform = src.transform.is_identity

    output_dir = Path("flair_output").resolve()
    output_dir.mkdir(exist_ok=True)

    inference_image_path = image_path
    if needs_pixel_transform:
        inference_image_path = output_dir / f"{image_path.stem}_pixel_coordinates.tif"
        with rasterio.open(image_path) as src:
            profile = src.profile.copy()
            profile.update(
                transform=from_origin(0, src.height, 1, 1),
                crs=None,
            )
            with rasterio.open(inference_image_path, "w", **profile) as dst:
                dst.write(src.read())
        print(f"Input has no affine transform; using pixel coordinates in {inference_image_path}")

    # Write the configuration required by the official FLAIR pipeline.
    config_path = output_dir / "flair_config.yaml"

    config_path.write_text(f"""
output_path: "{output_dir}"
output_name: "segmentation"

input_img_path: "{inference_image_path}"
channels: [1, 2, 3]

img_pixels_detection: 512
margin: 128
output_type: "argmax"
n_classes: 19

model_weights: "{weights}"

model_framework:
  model_provider: SegmentationModelsPytorch
  SegmentationModelsPytorch:
    encoder_decoder: resnet34_unet


batch_size: 2
use_gpu: true
num_worker: 0

write_dataframe: false

norma_task:
  - norm_type: custom
    norm_means: [105.08, 110.87, 101.82]
    norm_stds: [52.17, 45.38, 44.00]
""")

    print("Running FLAIR inference...")

    subprocess.run(
        ["flair-detect", f"--conf={config_path}"],
        check=True,
    )

    # Find the segmentation raster generated by FLAIR.
    results = list(output_dir.glob("segmentation*.tif"))

    if not results:
        sys.exit(
            f"No segmentation TIFF found in {output_dir}. "
            "Check the FLAIR command output."
        )

    segmentation_path = results[0]

    with rasterio.open(segmentation_path) as src:
        seg = src.read(1)

    print("Segmentation shape:", seg.shape)
    print("Classes:")
    for class_id, label in enumerate(CLASSES):
        print(f"{class_id:2d}: {label}")

    # Save the class-index array.
    np.save(output_dir / "segmentation.npy", seg)

    # Read the original RGB image.
    with rasterio.open(image_path) as src:
        original = src.read([1, 2, 3]).transpose(1, 2, 0)

    # Generate a reproducible random color for each class.
    np.random.seed(0)
    colors = np.random.randint(
        0, 255, size=(19, 3), dtype=np.uint8
    )

    # FLAIR argmax predictions use channel indices 0..18.
    mask_rgb = colors[np.clip(seg, 0, 18)]

    overlay = (
        0.5 * original.astype(np.float32)
        + 0.5 * mask_rgb.astype(np.float32)
    ).clip(0, 255).astype(np.uint8)

    Image.fromarray(overlay).save(
        output_dir / "segmentation_overlay.jpg"
    )

    print(f"\nSegmentation raster: {segmentation_path}")
    print(f"Class array:         {output_dir / 'segmentation.npy'}")
    print(f"Overlay:             {output_dir / 'segmentation_overlay.jpg'}")


if __name__ == "__main__":
    main()